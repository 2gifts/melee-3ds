"""Generate port/3ds/name_glyphs.h: which Unicode characters the game's text font can show, and how.

SIS text (the game's text, sysdolphin's sislib) turns each Shift-JIS character into a glyph by searching the 287
Shift-JIS codes of lbl_8040C8C0 (src/sysdolphin/baselib/hsd_3A76.c); the matching entry of HSD_SisLib_8040C680 is the
glyph code, 0x2000 + the index into HSD_SisLib_FontAtlas. A code that is not in the table is dropped. This reads both
tables from the decomp and writes, sorted by code point:
  name_glyphs[]  {code point, Shift-JIS code, atlas index} for every glyph (full-width ASCII, kana, some punctuation
                 and kanji);
  name_fold[]    {code point, replacement} for characters the font lacks but that read well as others: Latin letters
                 with accents (NFKD's base letter, and a few by hand: ß -> ss), half-width katakana (the full-width
                 ones); the combining voicing marks fold to nothing.

    python tools/gen_name_glyphs.py            # writes port/3ds/name_glyphs.h
    python tools/gen_name_glyphs.py --out F    # writes F instead (tools/test_name_glyphs.py compares)
"""
import argparse
import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DECOMP = ROOT.parent / 'src/sysdolphin/baselib/hsd_3A76.c'
OUT = ROOT / 'port/3ds/name_glyphs.h'
GLYPHS = 287
# Letters NFKD does not reduce to ASCII (or reduces to more than one letter).
MANUAL = {'ß': 'ss', 'æ': 'ae', 'Æ': 'AE', 'ø': 'o', 'Ø': 'O', 'đ': 'd', 'Đ': 'D', 'ł': 'l', 'Ł': 'L', 'œ': 'oe',
          'Œ': 'OE', 'ı': 'i', 'ħ': 'h', 'Ħ': 'H', 'ŧ': 't', 'Ŧ': 'T', 'ŋ': 'n', 'Ŋ': 'N', 'ĸ': 'k', 'ð': 'd', 'Ð': 'D',
          'þ': 'th', 'Þ': 'TH', 'ſ': 's', 'ŉ': 'n'}


def table(text, name):
    m = re.search(r'u8 ' + name + r'\[0x240\] = \{(.*?)\};', text, re.S)
    if not m:
        raise SystemExit(f'{name} not found in {DECOMP}')
    return [int(x, 16) for x in re.findall(r'0x[0-9A-Fa-f]{2}', m.group(1))]


def build():
    text = DECOMP.read_text(encoding='utf-8', errors='replace')
    sjis_bytes, glyph_bytes = table(text, 'lbl_8040C8C0'), table(text, 'HSD_SisLib_8040C680')
    glyphs = {}
    for i in range(GLYPHS):
        sjis = sjis_bytes[2 * i] << 8 | sjis_bytes[2 * i + 1]
        code = glyph_bytes[2 * i] << 8 | glyph_bytes[2 * i + 1]
        atlas = code - 0x2000
        if not 0 <= atlas < GLYPHS:
            raise SystemExit(f'entry {i}: glyph code {code:#x} is not in the atlas')
        ch = bytes((sjis >> 8, sjis & 0xFF)).decode('cp932')
        glyphs.setdefault(ord(ch), (sjis, atlas))
    # sanity checks against what the bottom screen's own font copy assumes (bottom_draw.c glyph_index)
    assert glyphs[0x3000] == (0x8140, 227), glyphs.get(0x3000)
    assert glyphs[0xFF0C] == (0x8143, 230), glyphs.get(0xFF0C)
    fold = {}
    for cp in range(0xC0, 0x180):
        ch = chr(cp)
        if ch in MANUAL:
            fold[cp] = MANUAL[ch]
            continue
        base = unicodedata.normalize('NFKD', ch)[0]
        if base.isascii() and base.isalpha():
            fold[cp] = base
    for ch, rep in MANUAL.items():
        fold.setdefault(ord(ch), rep)
    for cp in range(0xFF66, 0xFF9E):   # half-width katakana -> full-width
        full = unicodedata.normalize('NFKC', chr(cp))
        if len(full) == 1 and ord(full[0]) in glyphs:
            fold[cp] = full
    for cp in (0x3099, 0x309A, 0xFF9E, 0xFF9F):   # voicing marks on their own: dropped
        fold[cp] = ''
    return glyphs, fold


def c_string(s):
    return '"' + ''.join(c if c.isascii() and c.isalnum() else '\\x%02X' % b for c in s for b in c.encode('utf-8')) + '"'


def render(glyphs, fold):
    lines = ['/* Generated by tools/gen_name_glyphs.py from the decomp\'s hsd_3A76.c; do not edit. */',
             '#ifndef NAME_GLYPHS_H', '#define NAME_GLYPHS_H', '#include <stdint.h>', '',
             '/* Every character the game\'s text font has: code point, Shift-JIS code, HSD_SisLib_FontAtlas index. */',
             'static const struct { uint32_t cp; uint16_t sjis, atlas; } name_glyphs[] = {']
    for cp in sorted(glyphs):
        sjis, atlas = glyphs[cp]
        lines.append(f'    {{0x{cp:04X}, 0x{sjis:04X}, {atlas}}},   /* {chr(cp) if cp > 0x7F else "?"} */'
                     if cp > 0x7F else f'    {{0x{cp:04X}, 0x{sjis:04X}, {atlas}}},')
    lines += ['};', '#define NAME_GLYPH_COUNT (sizeof(name_glyphs) / sizeof(name_glyphs[0]))', '',
              '/* Characters the font lacks, folded to ones it has ("" = drop the character). */',
              'static const struct { uint32_t cp; const char *to; } name_fold[] = {']
    for cp in sorted(fold):
        lines.append(f'    {{0x{cp:04X}, {c_string(fold[cp])}}},')
    lines += ['};', '#define NAME_FOLD_COUNT (sizeof(name_fold) / sizeof(name_fold[0]))', '', '#endif', '']
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--out', default=str(OUT))
    args = ap.parse_args()
    glyphs, fold = build()
    Path(args.out).write_text(render(glyphs, fold), encoding='utf-8')
    print(f'{len(glyphs)} glyphs, {len(fold)} folds -> {args.out}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
